void HudOverlay::init(DeviceContext* deviceCtx, uint32_t w, uint32_t h) {
    ctx = deviceCtx;
    ctx->makeCurrent();
    width = w;
    height = h;
    pixels.assign(static_cast<size_t>(w) * h * 4, 0);

    image = createImage(ctx->physical, ctx->device, w, h, VK_FORMAT_R8G8B8A8_UNORM,
                        VK_IMAGE_USAGE_TRANSFER_DST_BIT | VK_IMAGE_USAGE_SAMPLED_BIT,
                        VK_MEMORY_PROPERTY_DEVICE_LOCAL_BIT, VK_IMAGE_TILING_OPTIMAL, true);

    VkDeviceSize bufSize = pixels.size();
    VkBufferCreateInfo bci{VK_STRUCTURE_TYPE_BUFFER_CREATE_INFO};
    bci.size = bufSize;
    bci.usage = VK_BUFFER_USAGE_TRANSFER_SRC_BIT;
    vkCheck(vkCreateBuffer(ctx->device, &bci, nullptr, &staging), "hud staging buf");
    VkMemoryRequirements req{};
    vkGetBufferMemoryRequirements(ctx->device, staging, &req);
    VkMemoryAllocateInfo mai{VK_STRUCTURE_TYPE_MEMORY_ALLOCATE_INFO};
    mai.allocationSize = req.size;
    mai.memoryTypeIndex = findMemoryType(ctx->physical, req.memoryTypeBits,
                                         VK_MEMORY_PROPERTY_HOST_VISIBLE_BIT | VK_MEMORY_PROPERTY_HOST_COHERENT_BIT);
    vkCheck(vkAllocateMemory(ctx->device, &mai, nullptr, &stagingMem), "hud staging mem");
    vkCheck(vkBindBufferMemory(ctx->device, staging, stagingMem, 0), "hud bind");
    vkCheck(vkMapMemory(ctx->device, stagingMem, 0, bufSize, 0, &stagingMapped), "hud map");

    VkCommandPoolCreateInfo pci{VK_STRUCTURE_TYPE_COMMAND_POOL_CREATE_INFO};
    pci.flags = VK_COMMAND_POOL_CREATE_RESET_COMMAND_BUFFER_BIT;
    pci.queueFamilyIndex = ctx->graphicsFamily;
    vkCheck(vkCreateCommandPool(ctx->device, &pci, nullptr, &pool), "hud pool");
    VkCommandBufferAllocateInfo cai{VK_STRUCTURE_TYPE_COMMAND_BUFFER_ALLOCATE_INFO};
    cai.commandPool = pool;
    cai.level = VK_COMMAND_BUFFER_LEVEL_PRIMARY;
    cai.commandBufferCount = 1;
    vkCheck(vkAllocateCommandBuffers(ctx->device, &cai, &cmd), "hud cmd");
    VkFenceCreateInfo fci{VK_STRUCTURE_TYPE_FENCE_CREATE_INFO};
    fci.flags = VK_FENCE_CREATE_SIGNALED_BIT;
    vkCheck(vkCreateFence(ctx->device, &fci, nullptr, &fence), "hud fence");
}

void HudOverlay::destroy() {
    if (!ctx) return;
    ctx->makeCurrent();
    ctx->waitIdle();
    image.destroy();
    if (stagingMapped) { vkUnmapMemory(ctx->device, stagingMem); stagingMapped = nullptr; }
    if (staging) vkDestroyBuffer(ctx->device, staging, nullptr);
    if (stagingMem) vkFreeMemory(ctx->device, stagingMem, nullptr);
    if (fence) vkDestroyFence(ctx->device, fence, nullptr);
    if (pool) vkDestroyCommandPool(ctx->device, pool, nullptr);
    staging = VK_NULL_HANDLE;
    stagingMem = VK_NULL_HANDLE;
    fence = VK_NULL_HANDLE;
    pool = VK_NULL_HANDLE;
    cmd = VK_NULL_HANDLE;
    ctx = nullptr;
}

void HudOverlay::setText(const std::string& text) {
    std::fill(pixels.begin(), pixels.end(), 0);
    // Semi-transparent dark panel background for readability
    const int panelH = std::min(static_cast<int>(height), 8 * 8 + 16); // up to 8 lines
    for (int y = 0; y < panelH; ++y) {
        for (uint32_t x = 0; x < width; ++x) {
            uint8_t* p = pixels.data() + (static_cast<size_t>(y) * width + x) * 4;
            p[0] = 10; p[1] = 12; p[2] = 18; p[3] = 200;
        }
    }

    int x = 8;
    int y = 8;
    const int scale = 2; // 16px glyphs via nearest doubling
    for (char c : text) {
        if (c == '\n') {
            x = 8;
            y += 8 * scale + 4;
            if (y + 8 * scale >= static_cast<int>(height)) break;
            continue;
        }
        // Draw scaled 2x
        if (c < 32 || c > 127) c = '?';
        const uint8_t* glyph = kFont8[c - 32];
        for (int row = 0; row < 8; ++row) {
            uint8_t bits = glyph[row];
            for (int col = 0; col < 8; ++col) {
                if (!(bits & (1u << col))) continue;
                for (int sy = 0; sy < scale; ++sy) {
                    for (int sx = 0; sx < scale; ++sx) {
                        int px = x + col * scale + sx;
                        int py = y + row * scale + sy;
                        if (px < 0 || py < 0 || px >= static_cast<int>(width) || py >= static_cast<int>(height))
                            continue;
                        uint8_t* p = pixels.data() + (static_cast<size_t>(py) * width + static_cast<size_t>(px)) * 4;
                        // Bright green metrics text
                        p[0] = 80; p[1] = 255; p[2] = 140; p[3] = 255;
                    }
                }
            }
        }
        x += 8 * scale + 2;
        if (x + 8 * scale >= static_cast<int>(width)) {
            x = 8;
            y += 8 * scale + 4;
        }
    }
}

void HudOverlay::upload() {
    ctx->makeCurrent();
    std::memcpy(stagingMapped, pixels.data(), pixels.size());

    vkCheck(vkWaitForFences(ctx->device, 1, &fence, VK_TRUE, UINT64_MAX), "hud wait");
    vkCheck(vkResetFences(ctx->device, 1, &fence), "hud reset");
    vkResetCommandBuffer(cmd, 0);
    VkCommandBufferBeginInfo bi{VK_STRUCTURE_TYPE_COMMAND_BUFFER_BEGIN_INFO};
    bi.flags = VK_COMMAND_BUFFER_USAGE_ONE_TIME_SUBMIT_BIT;
    vkBeginCommandBuffer(cmd, &bi);

    transitionImage(cmd, image.image, VK_IMAGE_LAYOUT_UNDEFINED, VK_IMAGE_LAYOUT_TRANSFER_DST_OPTIMAL,
                    VK_PIPELINE_STAGE_FRAGMENT_SHADER_BIT, VK_PIPELINE_STAGE_TRANSFER_BIT,
                    VK_ACCESS_SHADER_READ_BIT, VK_ACCESS_TRANSFER_WRITE_BIT);

    VkBufferImageCopy copy{};
    copy.imageSubresource = {VK_IMAGE_ASPECT_COLOR_BIT, 0, 0, 1};
    copy.imageExtent = {width, height, 1};
    vkCmdCopyBufferToImage(cmd, staging, image.image, VK_IMAGE_LAYOUT_TRANSFER_DST_OPTIMAL, 1, &copy);

    transitionImage(cmd, image.image, VK_IMAGE_LAYOUT_TRANSFER_DST_OPTIMAL, VK_IMAGE_LAYOUT_SHADER_READ_ONLY_OPTIMAL,
                    VK_PIPELINE_STAGE_TRANSFER_BIT, VK_PIPELINE_STAGE_FRAGMENT_SHADER_BIT,
                    VK_ACCESS_TRANSFER_WRITE_BIT, VK_ACCESS_SHADER_READ_BIT);

    vkEndCommandBuffer(cmd);
    VkSubmitInfo si{VK_STRUCTURE_TYPE_SUBMIT_INFO};
    si.commandBufferCount = 1;
    si.pCommandBuffers = &cmd;
    vkCheck(vkQueueSubmit(ctx->graphicsQueue, 1, &si, fence), "hud submit");
    vkCheck(vkWaitForFences(ctx->device, 1, &fence, VK_TRUE, UINT64_MAX), "hud drain");
}
